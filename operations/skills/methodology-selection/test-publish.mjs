// Tests for the publishing gate (phase 2 slice 1). Run: node test-publish.mjs
import { plan as plan0, rewriteLinks, write } from "./publish.mjs";
import { mkdtempSync, existsSync, rmSync } from "node:fs";
import { tmpdir } from "node:os";
import { parseFrontmatter } from "./ee.mjs";
const plan = (v, m) => plan0(v, m, parseFrontmatter);
import { join, dirname } from "node:path";
import { writeFileSync, readFileSync } from "node:fs";
const V = join(dirname(new URL(import.meta.url).pathname), "fixtures/publish-vault");
const M = { include: ["everything-ecosystem/**/*.md", "projects/**/*.md", "clients/**/*.md"], exclude: [] };
let failed = 0;
const ok = (n, c) => { if (!c) failed++; console.log(`${c ? "✓" : "✗"} ${n}`); };
const r = plan(V, M);
const pub = r.published.map((p) => p.file), why = (f) => r.refused.find((x) => x.file.endsWith(f))?.why.join(" ") ?? "";
ok("publishes a flagged catalog entry", pub.includes("everything-ecosystem/catalog/methodologies/ok-entry.md"));
ok("publishes an assignment marked visibility: public", pub.includes("everything-ecosystem/register/A-002-public.md"));
ok("R1 refuses files outside everything-ecosystem even when globbed", /R1/.test(why("projects/x/internal.md")) && /R1/.test(why("clients/secret-note.md")));
ok("R2 refuses ip-sensitivity high", /R2/.test(why("sensitive.md")));
ok("R2 refuses _archive", /R2/.test(why("_archive/old.md")));
ok("R3 refuses a file without publish: true", /R3/.test(why("no-flag.md")));
ok("R4 refuses a private-by-default assignment", /R4/.test(why("A-001-private.md")));
ok("R5 refuses raw captures", /R5/.test(why("references/raw.md")));
ok("exactly two files published", pub.length === 2);
const okFile = join(V, "everything-ecosystem/catalog/methodologies/ok-entry.md"), orig = readFileSync(okFile, "utf8");
writeFileSync(okFile, orig + "\n![[secret-note]]\n");
const r2 = plan(V, M); writeFileSync(okFile, orig);
ok("an embed of an unpublished note fails the run", !r2.ok && /secret-note/.test(r2.errors[0]?.msg));
const t = rewriteLinks("See [[secret-note]] and [[ok-entry|the entry]].", pub);
ok("links to unpublished notes become plain text; published links become site links", t === "See secret-note and [the entry](/catalog/methodologies/ok-entry/).");
const r3 = plan(V, { ...M, "private-terms": ["Public entry"] });
ok("R6 refuses a page that names a private term", /R6/.test(r3.refused.find((x) => x.file.endsWith("ok-entry.md"))?.why.join(" ") ?? ""));
const r4 = plan(V, { ...M, "use-case-terms": ["Public assignment"] });
ok("R7 refuses a page that refers to a use case", /R7/.test(r4.refused.find((x) => x.file.endsWith("A-002-public.md"))?.why.join(" ") ?? ""));
// writer
const O = mkdtempSync(join(tmpdir(), "site-"));
const okPath = join(V, "everything-ecosystem/catalog/methodologies/ok-entry.md"), okOrig = readFileSync(okPath, "utf8");
writeFileSync(okPath, okOrig.replace("publish: true", "publish: true\nevidence: [A-001, A-002]\nratified-by: the owner"));
const w1 = write(V, plan(V, M), O, parseFrontmatter); writeFileSync(okPath, okOrig);
const outOk = readFileSync(join(O, "src/content/docs/catalog/methodologies/ok-entry.md"), "utf8");
ok("writer replaces private assignment ids with a count and keeps public ones", /"evidence": \[\s*"A-002"\s*\]/.test(outOk) && /"evidence-private-count": 1/.test(outOk));
ok("writer strips ratified-by and publish fields", !/ratified-by|"publish"/.test(outOk));
ok("writer rewrites links (unpublished note is plain text)", /See secret-note and \[ok-entry\]/.test(outOk));
writeFileSync(join(V, "everything-ecosystem/register/A-002-public.md"), readFileSync(join(V, "everything-ecosystem/register/A-002-public.md"), "utf8").replace("visibility: public", "visibility: private"));
const w2 = write(V, plan(V, M), O, parseFrontmatter);
writeFileSync(join(V, "everything-ecosystem/register/A-002-public.md"), readFileSync(join(V, "everything-ecosystem/register/A-002-public.md"), "utf8").replace("visibility: private", "visibility: public"));
ok("writer removes a page that is no longer published", w2.removed.includes("register/A-002-public.md") && !existsSync(join(O, "src/content/docs/register/A-002-public.md")));
ok("public report lists no refused files", !/Refused|secret-note|A-001/.test(readFileSync(join(O, "publish-report.md"), "utf8")));
rmSync(O, { recursive: true });
process.exit(failed ? 1 : 0);
