// Admit every term through the same pipeline (Torian, 2026-10-31: adding a term always runs it; nobody asks).
//
//   node schema/terms/admit.ts           run the pipeline and write schema/terms/admitted.json
//   node schema/terms/admit.ts --check   exit 1 if a term fails, or admitted.json differs from a fresh run
//
// For each term: freeze (hash) -> valid test? -> cross-run against every term at its level -> name its Lean
// theorems (each must exist in lean/; the lean CI job proves them) -> record as proposed, with each prediction
// marked confirmed or refuted. A refuted prediction is a finding, not a failure: the definition says what it says.

import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { freeze, passSet, relation, validTest, type Base, type Relation, type Term } from "./engine.ts";
import { encounterCases, membershipCases, relationshipCases } from "./levels.ts";
import { TERMS } from "./terms.ts";

const here = new URL(".", import.meta.url).pathname;
const repo = join(here, "../..");
const out = join(here, "admitted.json");

const CASES: Record<string, Base[]> = { membership: membershipCases(), relationship: relationshipCases(), encounter: encounterCases() };

function leanSource(): string {
  const d = join(repo, "lean/Naive");
  return existsSync(d) ? readdirSync(d).filter((f) => f.endsWith(".lean")).map((f) => readFileSync(join(d, f), "utf8")).join("\n") : "";
}

export function admitAll(): { record: unknown; problems: string[] } {
  const problems: string[] = [];
  const lean = leanSource();
  const terms = TERMS as Term<Base>[];
  const ids = terms.map((t) => t.id);
  if (new Set(ids).size !== ids.length) problems.push("two terms share an id (admission keeps ids unique)");
  const sets = new Map(terms.map((t) => [t.id, passSet(t, CASES[t.level] ?? [])]));
  const entries = terms.map((t) => {
    const cases = CASES[t.level];
    if (!cases) { problems.push(`${t.id}: no cases for level ${t.level}`); return null; }
    const valid = validTest(t, cases);
    problems.push(...valid);
    const relations: Record<string, Relation> = {};
    for (const o of terms) if (o.id !== t.id && o.level === t.level) relations[o.id] = relation(sets.get(t.id)!, sets.get(o.id)!);
    const predictions = Object.entries(t.predicts ?? {}).map(([other, expected]) => {
      const found = relations[other] ?? "cross-level: needs a lift";
      return { other, expected, found, confirmed: found === expected };
    });
    for (const thm of t.lean ?? []) if (!new RegExp(`theorem\\s+${thm}\\b`).test(lean)) problems.push(`${t.id}: Lean theorem ${thm} is not in lean/Naive`);
    return {
      id: t.id, label: t.label, level: t.level, kind: t.kind, meaning: t.meaning, status: "proposed",
      hash: freeze(t),
      properties: t.props.map((p) => ({ id: p.id, says: p.says, ...(p.permission ? { permission: true } : {}) })),
      rule: t.ruleSays ?? "every property, and P7 (confirmed facts)",
      valid: valid.length === 0,
      passes: sets.get(t.id)!.size,
      relations, predictions, lean: t.lean ?? [], sources: t.sources,
    };
  }).filter(Boolean);
  return {
    record: { note: "Generated by node schema/terms/admit.ts. Every term: frozen, checked as a valid test, cross-run at its level over seeded cases, Lean theorems named (proved by the lean job). Status stays proposed until a person decides. Pass counts reflect the generators, not the world; only the relations mean anything.", terms: entries },
    problems,
  };
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const { record, problems } = admitAll();
  const text = JSON.stringify(record, null, 2) + "\n";
  for (const p of problems) console.log(`FAIL ${p}`);
  if (process.argv.includes("--check")) {
    const same = existsSync(out) && readFileSync(out, "utf8") === text;
    if (!same) console.log("FAIL schema/terms/admitted.json differs from a fresh run (run node schema/terms/admit.ts)");
    process.exit(problems.length || !same ? 1 : 0);
  }
  writeFileSync(out, text);
  const r = record as { terms: { id: string; predictions: { other: string; expected: string; found: string; confirmed: boolean }[] }[] };
  for (const t of r.terms) for (const p of t.predictions) console.log(`${p.confirmed ? "confirmed" : "REFUTED  "}  ${t.id} ${p.expected} ${p.other} (found ${p.found})`);
  console.log(problems.length ? `${problems.length} problem(s)` : `${r.terms.length} terms admitted as proposed`);
  process.exit(problems.length ? 1 : 0);
}
