// Generator for the PCF side of the link between roles and APQC's framework (EE-232),
// packages/naive/src/functions/pcf-roles.json. The role side is the source: each role in the library names the PCF
// elements it answers for in its pcf field, with its RACI part. draft reads every role.json in the library and turns
// the links around, one entry per element with the roles linked to it, accountable first, then responsible, consulted
// and informed, each by role id. An element named by no role is left out. format writes one element per line, so
// the same library always gives the same bytes. scripts/pcf-roles.ts runs both and writes the file, or with --check
// fails when the file is stale. A role that names an element pcf.json lacks is refused;
// packages/naive/src/checks/check-roles.ts reports it with the role's file.
import { join } from "node:path";
import { cli, readJson, repo, validate } from "./generate.ts";
import { loadRoles } from "../agents/roles.ts";
import { byHierarchy } from "./pcf.ts";
import type { Pcf, PcfRoles } from "../../records/types/records.d.ts";

export const record = "pcf-roles";
export const FILE = "packages/naive/src/functions/pcf-roles.json";
const PCF = "packages/naive/src/functions/pcf.json";
type Link = PcfRoles["elements"][number]["roles"][number];
const RACI: Link["raci"][] = ["accountable", "responsible", "consulted", "informed"];
export const NOTE = "Generated by scripts/pcf-roles.ts, through packages/naive/src/engine/generators/pcf-roles.ts, from the pcf field of every role in packages/naive/src/roles/ (EE-232); never edit it by hand. The role side is the source, so the link between roles and PCF elements is held both ways and cannot drift: node scripts/pcf-roles.ts --check fails when this file is stale. Keep APQC's attribution with every copy.";

export const describe = () => ({ record, ask: [], derived: { elements: "every PCF element some library role names in its pcf field, with those roles and their RACI part, from packages/naive/src/roles/<id>/role.json", order: "elements by hierarchy id; roles accountable, responsible, consulted, informed, then by id" } });

/** The element side, from the library under root; the generator takes no answers, since the roles are its input. */
export function draft(answers: unknown = {}, { root = repo }: { root?: string } = {}) {
  void answers;
  const pcf = readJson(join(root, PCF)) as Pcf | null;
  if (!pcf) return { ok: false, record, errors: [`${PCF} is missing`] };
  const known = new Set(pcf.elements.map((e) => e.id));
  const links = new Map<string, Link[]>();
  const errors: string[] = [];
  for (const role of loadRoles(undefined, root).values()) for (const { id, raci } of role.pcf ?? []) {
    if (!known.has(id)) { errors.push(`${role.id} names PCF ${id}, which ${PCF} does not have`); continue; }
    links.set(id, [...(links.get(id) ?? []), { role: role.id, raci }]);
  }
  const elements = [...links].map(([id, roles]) => ({ id, roles: roles.sort((a, b) => RACI.indexOf(a.raci) - RACI.indexOf(b.raci) || (a.role < b.role ? -1 : a.role > b.role ? 1 : 0)) }))
    .sort((a, b) => byHierarchy({ id: a.id, name: "", pcf: 0, level: 1 }, { id: b.id, name: "", pcf: 0, level: 1 }));
  const rec: PcfRoles = { pcf_version: pcf.version, attribution: pcf.attribution, note: NOTE, elements };
  const v = validate(record, rec);
  return { ok: v.ok && !errors.length, record, file: FILE, draft: rec, errors: [...v.errors, ...errors] };
}

/** The file's bytes: the header as indented JSON, then one element per line. */
export function format(rec: PcfRoles): string {
  const { elements, ...header } = rec;
  const head = JSON.stringify(header, null, 2).slice(0, -2);
  const line = (e: PcfRoles["elements"][number]) => `    {"id": ${JSON.stringify(e.id)}, "roles": [${e.roles.map((r) => `{"role": ${JSON.stringify(r.role)}, "raci": ${JSON.stringify(r.raci)}}`).join(", ")}]}`;
  return `${head},\n  "elements": ${elements.length ? `[\n${elements.map(line).join(",\n")}\n  ]` : "[]"}\n}\n`;
}

if (import.meta.url === `file://${process.argv[1]}`) process.exitCode = await cli({ record, describe, draft });
