// Ties the Lean model of the digital worker statechart (packages/naive/lean/Naive/Workers.lean) to the TypeScript
// (worker-state.ts), EE-235. It runs every phase, event and actor through the TypeScript `transition` and writes each
// result as a Lean `example` proved by `decide`, so `lake build` checks that the Lean model gives the same answer.
// The machine is finite, so the cases are all of it: 5 phases by 6 events by 2 actors.
//
//   node packages/naive/src/engine/agents/worker-cases.ts           write packages/naive/lean/Naive/Generated/WorkerCases.lean
//   node packages/naive/src/engine/agents/worker-cases.ts --check   exit 1 when the committed file differs from a fresh run
//
// A change to the TypeScript table changes the file, so --check fails until it is regenerated, and the regenerated
// file fails `lake build` unless the Lean model agrees. The TypeScript event `end` is `finish` in Lean.

import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { ACTORS, EVENTS, PHASES, transition } from "./worker-state.ts";
import type { WorkerEvent } from "./worker-state.ts";

export const OUTPUT = "packages/naive/lean/Naive/Generated/WorkerCases.lean";

const leanEvent = (e: WorkerEvent): string => (e === "end" ? "finish" : e);

/** The Lean file: one example per phase, event and actor. */
export function render(): string {
  const out = [
    "/-",
    "  Generated by `node packages/naive/src/engine/agents/worker-cases.ts` from",
    "  `packages/naive/src/engine/agents/worker-state.ts`. Never edited by hand: `--check` fails when this file differs",
    "  from a fresh run. Each example is a result of the TypeScript, and `decide` checks that the Lean model in",
    "  `Naive/Workers.lean` gives the same one.",
    "-/",
    "import Naive.Workers",
    "",
    "namespace Workers.Cases",
    "",
    "open Workers",
    "",
    `/-! ## transition: ${PHASES.length} phases by ${EVENTS.length} events by ${ACTORS.length} actors -/`,
    "",
  ];
  for (const p of PHASES) for (const e of EVENTS) for (const a of ACTORS)
    out.push(`example : transition .${p} .${leanEvent(e)} .${a} = .${transition(p, e, a).to} := by decide`);
  out.push("", "end Workers.Cases", "");
  return out.join("\n");
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const out = join(new URL(".", import.meta.url).pathname, "../../../../..", OUTPUT);
  const text = render();
  if (process.argv.includes("--check")) {
    let committed = "";
    try { committed = readFileSync(out, "utf8"); } catch { committed = ""; }
    if (committed !== text) { console.error(`${OUTPUT} is stale: run node packages/naive/src/engine/agents/worker-cases.ts`); process.exit(1); }
    console.log(`${OUTPUT} matches worker-state.ts`);
  } else {
    writeFileSync(out, text);
    console.log(`wrote ${OUTPUT}`);
  }
}
